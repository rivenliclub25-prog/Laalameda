-- =====================================================================
--  La Alameda — códigos numéricos de producto (fase P1b del POS)
--
--  Requisito: haber ejecutado antes catalogo.sql.
--  Cómo usarlo: Supabase → SQL Editor → New query → pega TODO este
--  archivo → Run. Se hace UNA sola vez: si lo vuelves a ejecutar, avisa
--  y no cambia nada.
--
--  Qué hace:
--    · Cambia el identificador de cada producto (antes un texto como
--      "cervezas-cana") por un CÓDIGO NUMÉRICO: 1, 2, 3…, en el orden de
--      la carta (categoría y posición).
--    · Los productos nuevos que se creen en el panel reciben solos el
--      siguiente número.
--    · Actualiza a la vez "qué productos lleva cada promo"
--      (promotion_items), para que nada se pierda.
--  Este código es el que usará el POS para identificar cada producto.
-- =====================================================================

do $codigos$
begin
  if exists (select 1 from public.catalogo_migraciones where id = 'p1b-codigos-productos') then
    raise notice 'Los productos ya tienen código numérico: no se cambia nada.';
    return;
  end if;

  -- 1. Código para cada producto, en el orden de la carta.
  alter table public.products add column codigo integer;
  update public.products p
  set codigo = x.n
  from (
    select pr.id, row_number() over (order by c.orden, c.id, pr.orden, pr.id) as n
    from public.products pr
    join public.menu_categories c on c.id = pr.categoria_id
  ) x
  where x.id = p.id;

  -- 2. Los productos de cada promo pasan a apuntar al código.
  alter table public.promotion_items add column product_codigo integer;
  update public.promotion_items pi
  set product_codigo = p.codigo
  from public.products p
  where p.id = pi.product_id;

  alter table public.promotion_items drop constraint promotion_items_pkey;
  alter table public.promotion_items drop constraint promotion_items_product_id_fkey;
  alter table public.promotion_items drop column product_id;
  alter table public.promotion_items rename column product_codigo to product_id;
  alter table public.promotion_items alter column product_id set not null;

  -- 3. El código pasa a ser el identificador del producto, y se numera solo.
  alter table public.products drop constraint products_pkey;
  alter table public.products drop column id;
  alter table public.products rename column codigo to id;
  alter table public.products alter column id set not null;
  alter table public.products add constraint products_pkey primary key (id);
  alter table public.products alter column id add generated by default as identity;
  perform setval(pg_get_serial_sequence('public.products', 'id'), (select coalesce(max(id), 0) + 1 from public.products), false);

  alter table public.promotion_items add constraint promotion_items_pkey primary key (promo_id, product_id);
  alter table public.promotion_items add constraint promotion_items_product_id_fkey
    foreign key (product_id) references public.products (id) on update cascade on delete cascade;

  insert into public.catalogo_migraciones (id) values ('p1b-codigos-productos');
  raise notice 'Productos numerados: %', (select count(*) from public.products);
end;
$codigos$;


