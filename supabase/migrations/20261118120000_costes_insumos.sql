-- ---------------------------------------------------------------------
-- 4. Importación del Excel: previsualizar (p_confirmar = false) o aplicar
--    p_filas: [{"fila": 3, "nombre": "Leche", "categoria": "Café", "formato": "1000 ml",
--               "cantidad_formato": 1000, "unidad_base": "ml", "precio_compra_sin_iva": 1.1}, …]
--    Los ingredientes se reconocen por el nombre (sin mayúsculas ni espacios de más).
--    Con un solo error no se aplica nada.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION "public"."admin_importar_insumos"("p_archivo" "text", "p_filas" "jsonb", "p_confirmar" boolean) RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  rec       record;
  x         jsonb;
  v_fila    integer;
  v_nombre  text;
  v_clave   text;
  v_cat     text;
  v_formato text;
  v_cant    numeric;
  v_uni     text;
  v_precio  numeric;
  v_coste   numeric;
  v_motivo  text;
  ex        public.insumos%rowtype;
  vistos    text[] := '{}';
  errores   jsonb := '[]'::jsonb;
  nuevos    jsonb := '[]'::jsonb;
  cambios   jsonb := '[]'::jsonb;
  iguales   integer := 0;
  validas   jsonb := '[]'::jsonb;
  v_informe jsonb;
  v_imp     uuid;
begin
  if not public.is_admin() then raise exception 'NO_ES_ADMIN'; end if;
  if p_filas is null or jsonb_typeof(p_filas) <> 'array' or jsonb_array_length(p_filas) = 0 then
    raise exception 'IMPORTACION_VACIA';
  end if;
  if jsonb_array_length(p_filas) > 2000 then raise exception 'IMPORTACION_DEMASIADO_GRANDE'; end if;

  if p_confirmar then
    -- Dos importaciones a la vez: la segunda espera y ve lo que hizo la primera.
    lock table public.insumos in share row exclusive mode;
  end if;

  for rec in select value as v, ordinality as n from jsonb_array_elements(p_filas) with ordinality loop
    x := rec.v;
    v_motivo := null;
    v_fila := case when jsonb_typeof(x -> 'fila') = 'number' then (x ->> 'fila')::numeric::integer else rec.n::integer end;
    v_nombre := btrim(regexp_replace(coalesce(x ->> 'nombre', ''), '\s+', ' ', 'g'));
    v_clave := lower(v_nombre);
    v_cat := nullif(btrim(coalesce(x ->> 'categoria', '')), '');
    v_formato := nullif(btrim(coalesce(x ->> 'formato', '')), '');
    v_uni := x ->> 'unidad_base';
    v_cant := case when jsonb_typeof(x -> 'cantidad_formato') = 'number' then (x ->> 'cantidad_formato')::numeric end;
    v_precio := case when jsonb_typeof(x -> 'precio_compra_sin_iva') = 'number' then (x ->> 'precio_compra_sin_iva')::numeric end;

    if v_nombre = '' then v_motivo := 'Falta el nombre';
    elsif length(v_nombre) > 120 then v_motivo := 'Nombre demasiado largo (máximo 120)';
    elsif v_clave = any (vistos) then v_motivo := 'Repetido en el archivo';
    elsif v_cant is null or v_cant <= 0 or v_cant >= 1000000000 then v_motivo := 'Cantidad del formato no válida';
    elsif v_uni is null or v_uni not in ('ml', 'g', 'ud') then v_motivo := 'Unidad no válida (ml, g o ud)';
    elsif v_precio is null or v_precio < 0 or v_precio >= 100000000 then v_motivo := 'Precio no válido';
    elsif v_cat is not null and length(v_cat) > 60 then v_motivo := 'Categoría demasiado larga (máximo 60)';
    elsif v_formato is not null and length(v_formato) > 120 then v_motivo := 'Formato demasiado largo (máximo 120)';
    end if;

    if v_motivo is null then
      select * into ex from public.insumos where lower(btrim(nombre)) = v_clave;
      if found and ex.unidad_base <> v_uni then
        v_motivo := format('Unidad distinta de la guardada (%s)', ex.unidad_base);
      end if;
    end if;

    if v_motivo is not null then
      errores := errores || jsonb_build_object('fila', v_fila, 'nombre', nullif(v_nombre, ''), 'motivo', v_motivo);
      continue;
    end if;
    vistos := vistos || v_clave;
    v_cant := round(v_cant, 3);
    v_precio := round(v_precio, 4);

    if ex.id is null then
      v_coste := round(v_precio / v_cant, 6);
      nuevos := nuevos || jsonb_build_object('fila', v_fila, 'nombre', v_nombre, 'categoria', v_cat,
                                             'cantidad_formato', v_cant, 'unidad_base', v_uni,
                                             'precio_compra_sin_iva', v_precio, 'coste_unitario', v_coste);
      validas := validas || jsonb_build_object('accion', 'nuevo', 'nombre', v_nombre, 'categoria', v_cat,
                                               'formato', v_formato, 'cantidad_formato', v_cant,
                                               'unidad_base', v_uni, 'precio', v_precio);
    elsif (ex.precio_compra_sin_iva, ex.cantidad_formato) is distinct from (v_precio, v_cant) then
      v_coste := round(v_precio / (v_cant * ex.rendimiento_pct / 100), 6);
      cambios := cambios || jsonb_build_object('fila', v_fila, 'id', ex.id, 'nombre', ex.nombre, 'unidad_base', v_uni,
                                               'precio_antes', ex.precio_compra_sin_iva, 'precio_despues', v_precio,
                                               'coste_antes', ex.coste_unitario, 'coste_despues', v_coste);
      validas := validas || jsonb_build_object('accion', 'cambio', 'id', ex.id, 'formato', v_formato,
                                               'cantidad_formato', v_cant, 'precio', v_precio);
    else
      iguales := iguales + 1;
    end if;
    ex := null;
  end loop;

  v_informe := jsonb_build_object('total', jsonb_array_length(p_filas), 'nuevos', nuevos, 'cambios', cambios,
                                  'iguales', iguales, 'errores', errores);
  if not p_confirmar or jsonb_array_length(errores) > 0 then
    return v_informe || jsonb_build_object('aplicada', false);
  end if;

  insert into public.costes_importaciones (tipo, nombre_archivo, filas, informe, creada_por)
  values ('insumos', left(nullif(btrim(coalesce(p_archivo, '')), ''), 200), p_filas, v_informe, auth.uid())
  returning id into v_imp;
  perform set_config('costes.importacion_id', v_imp::text, true);

  for x in select value from jsonb_array_elements(validas) loop
    if x ->> 'accion' = 'nuevo' then
      insert into public.insumos (nombre, categoria, formato, cantidad_formato, unidad_base, precio_compra_sin_iva)
      values (x ->> 'nombre', x ->> 'categoria', x ->> 'formato', (x ->> 'cantidad_formato')::numeric,
              x ->> 'unidad_base', (x ->> 'precio')::numeric);
    else
      update public.insumos
      set precio_compra_sin_iva = (x ->> 'precio')::numeric,
          cantidad_formato = (x ->> 'cantidad_formato')::numeric,
          formato = coalesce(x ->> 'formato', formato)
      where id = (x ->> 'id')::integer;
    end if;
  end loop;

  perform set_config('costes.importacion_id', '', true);
  return v_informe || jsonb_build_object('aplicada', true, 'importacion_id', v_imp);
end;
$$;


