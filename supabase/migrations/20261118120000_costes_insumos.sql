-- =====================================================================
--  Rentabilidad R1: ingredientes (insumos) con su coste y su histórico
--  (RENTABILIDAD.md, secciones 7 y 8)
--
--  - insumos: lo que se compra, con precio de compra SIN IVA y formato.
--    coste_unitario lo calcula la base de datos (nunca queda desfasado).
--  - insumo_precios: histórico de precios. Se rellena solo y no se puede
--    modificar ni borrar.
--  - costes_importaciones: registro de cada importación del Excel.
--  - admin_importar_insumos(): previsualiza o aplica una importación.
--  Todo solo para admins: camareros, socios y la web pública no ven costes.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Tablas
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "public"."insumos" (
    "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- el código del ingrediente
    "nombre" "text" NOT NULL,
    "categoria" "text",
    "proveedor" "text",
    "formato" "text",
    "cantidad_formato" numeric(12,3) NOT NULL,                    -- total del formato en unidad base
    "unidad_base" "text" NOT NULL,
    "rendimiento_pct" numeric(5,2) DEFAULT 100 NOT NULL,          -- lo aprovechable de lo comprado
    "precio_compra_sin_iva" numeric(12,4) NOT NULL,
    "coste_unitario" numeric(12,6) GENERATED ALWAYS AS
        (round("precio_compra_sin_iva" / ("cantidad_formato" * "rendimiento_pct" / 100), 6)) STORED,
    "activo" boolean DEFAULT true NOT NULL,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "updated_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "updated_by" "uuid" REFERENCES "auth"."users"("id") ON DELETE SET NULL,
    CONSTRAINT "insumos_nombre_check" CHECK (length(btrim("nombre")) BETWEEN 1 AND 120),
    CONSTRAINT "insumos_categoria_check" CHECK ("categoria" IS NULL OR length("categoria") <= 60),
    CONSTRAINT "insumos_proveedor_check" CHECK ("proveedor" IS NULL OR length("proveedor") <= 120),
    CONSTRAINT "insumos_formato_check" CHECK ("formato" IS NULL OR length("formato") <= 120),
    CONSTRAINT "insumos_cantidad_formato_check" CHECK ("cantidad_formato" > 0),
    CONSTRAINT "insumos_unidad_base_check" CHECK ("unidad_base" IN ('ml', 'g', 'ud')),
    CONSTRAINT "insumos_rendimiento_pct_check" CHECK ("rendimiento_pct" > 0 AND "rendimiento_pct" <= 100),
    CONSTRAINT "insumos_precio_check" CHECK ("precio_compra_sin_iva" >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS "insumos_nombre_key" ON "public"."insumos" (lower(btrim("nombre")));

CREATE TABLE IF NOT EXISTS "public"."costes_importaciones" (
    "id" "uuid" DEFAULT gen_random_uuid() PRIMARY KEY,
    "tipo" "text" DEFAULT 'insumos' NOT NULL,
    "nombre_archivo" "text",
    "filas" "jsonb" NOT NULL,
    "informe" "jsonb" NOT NULL,
    "creada_por" "uuid" REFERENCES "auth"."users"("id") ON DELETE SET NULL,
    "creada_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    CONSTRAINT "costes_importaciones_tipo_check" CHECK ("tipo" IN ('insumos')),
    CONSTRAINT "costes_importaciones_archivo_check" CHECK ("nombre_archivo" IS NULL OR length("nombre_archivo") <= 200)
);

CREATE TABLE IF NOT EXISTS "public"."insumo_precios" (
    "id" bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    "insumo_id" integer NOT NULL REFERENCES "public"."insumos"("id") ON DELETE RESTRICT,
    "precio_compra_sin_iva" numeric(12,4) NOT NULL,
    "cantidad_formato" numeric(12,3) NOT NULL,
    "rendimiento_pct" numeric(5,2) NOT NULL,
    "coste_unitario" numeric(12,6) NOT NULL,
    "vigente_desde" timestamp with time zone DEFAULT "now"() NOT NULL,
    "origen" "text" NOT NULL,
    "importacion_id" "uuid" REFERENCES "public"."costes_importaciones"("id") ON DELETE RESTRICT,
    "creado_por" "uuid" REFERENCES "auth"."users"("id") ON DELETE SET NULL,
    CONSTRAINT "insumo_precios_origen_check" CHECK ("origen" IN ('importacion', 'manual'))
);
CREATE INDEX IF NOT EXISTS "insumo_precios_insumo_idx" ON "public"."insumo_precios" ("insumo_id", "vigente_desde" DESC);

ALTER TABLE "public"."insumos" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "public"."insumo_precios" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "public"."costes_importaciones" ENABLE ROW LEVEL SECURITY;


