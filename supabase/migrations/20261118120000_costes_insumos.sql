-- Histórico: una línea al crear el ingrediente y cada vez que cambia lo que fija su coste.
-- Una importación lo marca con su id (ajuste local de la transacción costes.importacion_id).
CREATE OR REPLACE FUNCTION "public"."_insumo_registrar_precio"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  v_imp uuid := nullif(current_setting('costes.importacion_id', true), '')::uuid;
begin
  if tg_op = 'UPDATE'
     and (new.precio_compra_sin_iva, new.cantidad_formato, new.rendimiento_pct)
         is not distinct from (old.precio_compra_sin_iva, old.cantidad_formato, old.rendimiento_pct) then
    return null;
  end if;
  insert into public.insumo_precios (insumo_id, precio_compra_sin_iva, cantidad_formato, rendimiento_pct,
                                     coste_unitario, origen, importacion_id, creado_por)
  values (new.id, new.precio_compra_sin_iva, new.cantidad_formato, new.rendimiento_pct, new.coste_unitario,
          case when v_imp is null then 'manual' else 'importacion' end, v_imp, auth.uid());
  return null;
end;
$$;

CREATE OR REPLACE TRIGGER "insumos_registrar_precio" AFTER INSERT OR UPDATE ON "public"."insumos"
  FOR EACH ROW EXECUTE FUNCTION "public"."_insumo_registrar_precio"();

-- El histórico no se toca (solo se permite que quien lo creó pase a null si se borra su cuenta).
CREATE OR REPLACE FUNCTION "public"."insumo_precios_inmutable"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  if tg_op = 'DELETE' then
    raise exception 'HISTORICO_INMUTABLE' using errcode = '42501';
  end if;
  if (new.id, new.insumo_id, new.precio_compra_sin_iva, new.cantidad_formato, new.rendimiento_pct,
      new.coste_unitario, new.vigente_desde, new.origen, new.importacion_id)
     is distinct from
     (old.id, old.insumo_id, old.precio_compra_sin_iva, old.cantidad_formato, old.rendimiento_pct,
      old.coste_unitario, old.vigente_desde, old.origen, old.importacion_id)
     or (new.creado_por is distinct from old.creado_por and new.creado_por is not null) then
    raise exception 'HISTORICO_INMUTABLE' using errcode = '42501';
  end if;
  return new;
end;
$$;

CREATE OR REPLACE TRIGGER "insumo_precios_inmutable" BEFORE DELETE OR UPDATE ON "public"."insumo_precios"
  FOR EACH ROW EXECUTE FUNCTION "public"."insumo_precios_inmutable"();


